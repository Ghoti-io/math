/* pi/4 rounded to a double (0x1.921fb54442d18p-1): the argument below which no
 * reduction is needed. */
#define GMATH_PIO4 0x1.921fb54442d18p-1

/* A double-double: hi + lo, with |lo| <= ulp(hi)/2 when normalized. */
typedef struct {
  double hi;
  double lo;
} gmath_dd;

static const uint64_t SIGN_BIT = 0x8000000000000000ull;
static const uint64_t ABS_MASK = 0x7fffffffffffffffull;
static const uint64_t INF_BITS = 0x7ff0000000000000ull;
static const uint64_t QNAN_BITS = 0x7ff8000000000000ull;

static uint64_t bits_of(double d) {
  uint64_t u;
  memcpy(&u, &d, sizeof u);
  return u;
}

static double double_of(uint64_t u) {
  double d;
  memcpy(&d, &u, sizeof d);
  return d;
}

/* An integer below 2^53 as a double, exactly, with no integer to double
 * conversion: 2^52 + k has the bit pattern 0x4330... | k for k < 2^52. */
static double small_to_double(uint64_t k) {
  const double two52 = 0x1p52;
  uint64_t hi = k >> 26;
  uint64_t lo = k & 0x3ffffffull;
  double dh = double_of(0x4330000000000000ull | hi) - two52;
  double dl = double_of(0x4330000000000000ull | lo) - two52;
  return dh * 0x1p26 + dl;
}

/* Knuth's FastTwoSum, valid when |a| >= |b| (every use here): s + e == a + b
 * exactly, s = fl(a + b). */
static gmath_dd fast_two_sum(double a, double b) {
  gmath_dd r;
  double s = a + b;
  double e = b - (s - a);
  r.hi = s;
  r.lo = e;
  return r;
}

/* Veltkamp's split: a == hi + lo, each with at most 26 significant bits. */
static void split(double a, double * hi, double * lo) {
  double t = 134217729.0 * a; /* 2^27 + 1 */
  double h = t - (t - a);
  *hi = h;
  *lo = a - h;
}

/* Dekker's product: p + e == a * b exactly, p = fl(a * b), barring overflow
 * and underflow, which the ranges here do not reach. */
static gmath_dd two_prod(double a, double b) {
  gmath_dd r;
  double ah, al, bh, bl;
  double p = a * b;
  split(a, &ah, &al);
  split(b, &bh, &bl);
  double e = ((ah * bh - p) + ah * bl + al * bh) + al * bl;
  r.hi = p;
  r.lo = e;
  return r;
}

/*
 * Reduction.  For a finite ax > pi/4, find the integer N nearest ax * 2/pi
 * and the remainder r = ax - N * pi/2, |r| <= pi/4, as a double-double.
 * Returns N mod 4.
 *
 * ax = m * 2^q with m a 53-bit integer.  ax * (2/pi) = m * 2^q * F, F the
 * binary fraction 0.b1 b2 b3 ...  A bit b_i of F contributes m * 2^(q-i) * b_i,
 * a multiple of 4 once i <= q - 2, so only bits past position 32*j0, with
 * 32*j0 <= q - 2, matter for the quadrant and the fraction.  Take 8 words
 * (256 bits) from there.  Their truncation changes the product by less than
 * 2^(53 + q - 32*(j0+8)) < 2^-168, against a fraction no smaller than about
 * 2^-62 for any double.  Shifting m left by sh = q - 32*j0 puts the binary
 * point of the 256-bit-fraction product on a word boundary: the word above
 * the fraction holds N mod 4 in its low two bits.
 */
static int reduce(double ax, double * rh, double * rl) {
  uint64_t b = bits_of(ax);
  int e = (int)(b >> 52); /* ax > pi/4 >= 2^-1 so e >= 1022 */
  uint64_t m = (b & 0xfffffffffffffull) | 0x10000000000000ull;
  int q = e - 1075;
  int t = q - 2;
  int j0 = t >= 0 ? t / 32 : -((-t + 31) / 32); /* floor(t / 32) */
  int sh = t - 32 * j0 + 2;                     /* 2 .. 33 */

  /* m << sh, as four 32-bit words, least significant first. */
  uint32_t mm[4];
  {
    int rem = sh & 31;
    int wsh = sh >> 5;
    uint64_t a0 = m & 0xffffffffull;
    uint64_t a1 = m >> 32;
    uint64_t t0 = a0 << rem;
    uint64_t t1 = (a1 << rem) + (t0 >> 32);
    uint32_t w[3];
    w[0] = (uint32_t)t0;
    w[1] = (uint32_t)t1;
    w[2] = (uint32_t)(t1 >> 32);
    mm[0] = mm[1] = mm[2] = mm[3] = 0;
    for (int i = 0; i < 3; i++) {
      mm[i + wsh] = w[i];
    }
  }

  /* The product with the 256-bit window of 2/pi. */
  uint32_t a[8];
  for (int i = 0; i < 8; i++) {
    a[i] = gmath_two_over_pi[j0 + 2 + 7 - i]; /* least significant first */
  }
  uint32_t res[12];
  for (int i = 0; i < 12; i++) {
    res[i] = 0;
  }
  for (int i = 0; i < 4; i++) {
    uint64_t carry = 0;
    for (int j = 0; j < 8; j++) {
      uint64_t cur = (uint64_t)res[i + j] + (uint64_t)mm[i] * a[j] + carry;
      res[i + j] = (uint32_t)cur;
      carry = cur >> 32;
    }
    res[i + 8] = (uint32_t)carry;
  }

  int n = (int)(res[8] & 3u);
  uint32_t f[8];
  for (int i = 0; i < 8; i++) {
    f[i] = res[i];
  }
  int negative = 0;
  if (f[7] & 0x80000000u) {
    /* fraction >= 1/2: round up to the next integer and use 1 - fraction. */
    n = (n + 1) & 3;
    negative = 1;
    uint64_t carry = 1;
    for (int i = 0; i < 8; i++) {
      uint64_t v = (uint64_t)(uint32_t)~f[i] + carry;
      f[i] = (uint32_t)v;
      carry = v >> 32;
    }
  }

  /* Normalize: the leading one of the 256-bit fraction to bit 255. */
  int lead = 255;
  while (lead > 0 && !((f[lead >> 5] >> (lead & 31)) & 1u)) {
    lead--;
  }
  int s = 255 - lead;
  int ws = s >> 5;
  int bs = s & 31;
  uint32_t g[8];
  for (int i = 0; i < 8; i++) {
    int k = i - ws;
    uint64_t v = 0;
    if (k >= 0) {
      v = (uint64_t)f[k] << bs;
      if (k > 0) {
        v |= (uint64_t)f[k - 1] >> (32 - bs); /* 32 - bs == 32 gives 0 */
      }
    }
    g[i] = (uint32_t)v;
  }
  uint64_t a1 = ((uint64_t)g[7] << 32) | g[6];
  uint64_t a2 = ((uint64_t)g[5] << 32) | g[4];

  /* fraction = a1 * 2^(-64-s) + a2 * 2^(-128-s): hi takes the top 53 bits of
   * a1, lo the next 53. */
  double hi = double_of(((uint64_t)(1022 - s) << 52) | ((a1 >> 11) & 0xfffffffffffffull));
  uint64_t lo_int = ((a1 & 0x7ffull) << 42) | (a2 >> 22);
  double lo = small_to_double(lo_int) * double_of((uint64_t)(1023 - 106 - s) << 52);
  if (negative) {
    hi = -hi;
    lo = -lo;
  }

  /* r = fraction * pi/2. */
  gmath_dd p = two_prod(hi, GMATH_PIO2_HI);
  double low = p.lo + (hi * GMATH_PIO2_LO + lo * GMATH_PIO2_HI);
  gmath_dd r = fast_two_sum(p.hi, low);
  *rh = r.hi;
  *rl = r.lo;
  return n;
}

/* Knuth's TwoSum: s + e == a + b exactly, in any order of magnitudes. */
static gmath_dd two_sum(double a, double b) {
  gmath_dd r;
  double s = a + b;
  double bb = s - a;
  double e = (a - (s - bb)) + (b - bb);
  r.hi = s;
  r.lo = e;
  return r;
}

/* The fast reduction takes arguments strictly below this, which bounds the
 * quotient n below 2^20 (x * 2/pi < 667,545) and so lets n * P1, n * P2 and
 * n * P3 (n of 20 bits, Pk of 33) be exact products. */
#define GMATH_CW_LIMIT 0x1p20

/* The remainder is declined when it is smaller than this: its error is a
 * fixed absolute amount (below), so the relative error grows as it shrinks.
 * Below 2^20 no double is closer than 2^-60 to a multiple of pi/2, so this
 * hands over only a small part of the doubles near one; it is a margin of the
 * proof, not a boundary a result can tell. */
#define GMATH_CW_MIN_R 0x1p-55

/* Added to 2/pi * x, it leaves round-to-nearest-even(2/pi * x) in the low
 * bits of the sum: 1.5 * 2^52, so the sum's ulp is 1 and its value is
 * 2^52 + 2^51 + n for any integer n below 2^31. */
#define GMATH_CW_MAGIC 0x1.8p52

/*
 * Fast reduction for pi/4 < ax < 2^20.  Gives the same n mod 4 and the same
 * remainder (rh, rl) as reduce(), to within 2^-79 |rh| in rl, or
 * declines (returns -1) and leaves the work to reduce().
 *
 * n is the nearest integer to ax * 2/pi, taken by the 2^52 + 2^51 trick: no
 * integer to double conversion, no x87.  The product and the sum are each
 * rounded, so n can be one off when ax * 2/pi is within about 2^-33 of a
 * half-integer; that case has |r| > pi/4 (or within 2^-33 of it) and is
 * declined by the range test at the end.  Where the test passes, |r| is below
 * the double pi/4, which is below the true pi/4, and so n is the nearest
 * integer exactly as reduce() takes it.
 *
 * With P1 + P2 + P3 + P4 = pi/2 (three parts of 33 bits and a double):
 *
 *   d  = ax - n*P1   exact.  n*P1 is exact (20 + 33 bits).  ax and n*P1 are
 *                    both multiples of ulp(ax) (ulp(ax) <= 2^-33 below 2^20 and
 *                    P1 is a multiple of 2^-32), and |d| is below 2^53 ulp(ax)
 *                    (|d| < pi/4 + n * 2^-33), so d needs at most 53 bits.
 *   t2 = n*P2, t3 = n*P3   exact (20 + 33 bits).
 *   (s, e1) = TwoSum(d, -t2); (s, e2) = TwoSum(s, -t3)   exact.
 *   t4 = n*P4        rounded: |t4| < 2^20 * 2^-103, so the error is below
 *                    2^-136.
 *   lo = (e1 + e2) - t4   rounded: |e1|, |e2| <= 2^-53 (|r| + 2^-45) and
 *                    |t4| < 2^-83, so the error is below 2^-106 |r| + 2^-135.
 *
 * and P4 stops at 2^-156, so the sum of the four parts misses pi/2 by less
 * than n * 2^-156 < 2^-136.  The absolute error of s + lo as the remainder is
 * therefore below 2^-106 |r| + 2^-134, and for |r| >= 2^-55 that is below
 * 2^-79 |r|.  The
 * remainder reduce() returns is good to 2^-106 |r|, so the two agree to
 * about 2^-79 |r| at the floor and to 2^-106 for ordinary r.  (Measured
 * against reduce() over 6e7 arguments and over the corpus's worst cases,
 * whose smallest |r| is 2^-60.5, they differ by at most 2^-87 |r|; the bound
 * above is the one relied on.)  Below the floor the fast path declines.
 */
static int reduce_fast(double ax, double * rh, double * rl) {
  double t = ax * GMATH_CW_INV_PIO2;
  t = t + GMATH_CW_MAGIC;
  int n = (int)(bits_of(t) & 0xffffffffu);
  double nd = t - GMATH_CW_MAGIC;
  double d = ax - nd * GMATH_CW_P1;
  gmath_dd a = two_sum(d, -(nd * GMATH_CW_P2));
  gmath_dd b = two_sum(a.hi, -(nd * GMATH_CW_P3));
  double lo = (a.lo + b.lo) - nd * GMATH_CW_P4;
  gmath_dd r = fast_two_sum(b.hi, lo);
  double mag = double_of(bits_of(r.hi) & ABS_MASK);
  if (!(mag >= GMATH_CW_MIN_R && mag <= GMATH_PIO4)) {
    return -1;
  }
  *rh = r.hi;
  *rl = r.lo;
  return n & 3;
}

/* The wide fast reduction takes 2^20 <= ax < this, which bounds n below
 * 2^29.35 (ax * 2/pi < 684,000,000) and so lets n * Qk (n of 30 bits, Qk of 23)
 * be an exact product. */
#define GMATH_CW2_LIMIT 0x1p30

/*
 * Fast reduction for 2^20 <= ax < 2^30: the same method as reduce_fast with
 * narrower parts, because n now has up to 30 bits.  Gives the same n mod 4 and
 * the same remainder as reduce(), to within 2^-79 |rh| in rl, or declines
 * (returns -1) and leaves the work to reduce().
 *
 * n comes from the same 2^52 + 2^51 trick.  The product ax * (2/pi) is off by
 * up to about 2^-22 now (2^-53 relative of a number below 2^30, twice, and the
 * rounding of the double 2/pi), so n can be one off when ax * 2/pi is within
 * 2^-22 of a half-integer.  The remainder is then pi/2 - |r_true| with
 * |r_true| <= pi/4, so |r| >= the true pi/4, above the double pi/4, and the
 * range test at the end declines it, exactly as in reduce_fast.  A remainder
 * that passes the test is below the double pi/4, which is below the true pi/4,
 * so n is the nearest integer, as reduce() takes it.
 *
 * With Q1 + ... + Q6 = pi/2 (Q1..Q5 of 23 bits, Q6 a double; Qk is a multiple
 * of 2^-22, 2^-46, 2^-70, 2^-94, 2^-119 for k = 1..5, and what is left of pi/2
 * after Q1..Qk is below 2^-23, 2^-47, 2^-71, 2^-95, 2^-119, the last being
 * half the unit of Q5):
 *
 *   d  = ax - n*Q1   exact.  n*Q1 is exact (30 + 23 bits).  ax >= 2^20 and
 *                    n*Q1 are both multiples of 2^-32 (ulp(ax) >= 2^-32 and Q1
 *                    is a multiple of 2^-22), and |d| < pi/4 + n * 2^-23 < 2^7
 *                    (n < 2^29.35 and pi/2 - Q1 < 2^-23, plus the n that is
 *                    one too large), so d is below 2^39 units of 2^-32.
 *   t2 = n*Q2, t3 = n*Q3, t4 = n*Q4, t5 = n*Q5   exact (30 + 23 bits).
 *   s2 = d - t2      exact, with no error term: the true result is
 *                    r + n * (pi/2 - Q1 - Q2) of magnitude below 2, a multiple
 *                    of 2^-46 (d is a multiple of 2^-32, t2 of 2^-46), so it
 *                    has at most 48 significant bits and is a double; a
 *                    subtraction whose exact result is a double is exact.
 *   (s3, e3) = TwoSum(s2, -t3); (s4, e4) = TwoSum(s3, -t4);
 *   (s5, e5) = TwoSum(s4, -t5)   exact.  |sk| < |r| (1 + 2^-52) + n * 2^-(24k - 1)
 *                    (the remainder of pi/2 after Q1..Qk, times n), so
 *                    |e3| <= 2^-53 |r| + 2^-94, |e4| <= 2^-53 |r| + 2^-118
 *                    and |e5| <= 2^-53 |r| + 2^-142, up to a factor 1 + 2^-52.
 *   t6 = n*Q6        rounded: |t6| < 2^-91, the error is below 2^-144.
 *   lo = (e3 + e4) + (e5 - t6)   three roundings, each of half an ulp of a
 *                    quantity below 2^-52 |r| + 2^-90, so the error is below
 *                    2^-104 |r| + 2^-142.
 *
 * and Q6 is within 2^-175 of the rest of pi/2, so the sum of the six misses
 * pi/2 by less than n * 2^-175 < 2^-145.  The absolute error of s5 + lo as the
 * remainder is therefore below 2^-104 |r| + 2^-141, and for |r| >= 2^-55 that
 * is below 2^-84 |r|, which is inside the 2^-79 |r| that reduce_fast relies on
 * (reduce() itself is good to 2^-106 |r|).  The remainder is declined below the
 * floor 2^-55 as in reduce_fast; below 2^30 the closest a double comes to a
 * multiple of pi/2 is about 2^-62, so the floor hands over only a few doubles.
 */
static int reduce_fast_wide(double ax, double * rh, double * rl) {
  double t = ax * GMATH_CW_INV_PIO2;
  t = t + GMATH_CW_MAGIC;
  int n = (int)(bits_of(t) & 0xffffffffu);
  double nd = t - GMATH_CW_MAGIC;
  double d = ax - nd * GMATH_CW2_Q1;
  double s2 = d - nd * GMATH_CW2_Q2;
  gmath_dd a = two_sum(s2, -(nd * GMATH_CW2_Q3));
  gmath_dd b = two_sum(a.hi, -(nd * GMATH_CW2_Q4));
  gmath_dd c = two_sum(b.hi, -(nd * GMATH_CW2_Q5));
  double lo = (a.lo + b.lo) + (c.lo - nd * GMATH_CW2_Q6);
  gmath_dd r = fast_two_sum(c.hi, lo);
  double mag = double_of(bits_of(r.hi) & ABS_MASK);
  if (!(mag >= GMATH_CW_MIN_R && mag <= GMATH_PIO4)) {
    return -1;
  }
  *rh = r.hi;
  *rl = r.lo;
  return n & 3;
}

/* The reduction every function uses: n mod 4, with (rh, rl) = ax - n*pi/2 for
 * the nearest integer n.  ax > pi/4. */
static int reduce_any(double ax, double * rh, double * rl) {
  if (ax < GMATH_CW_LIMIT) {
    int n = reduce_fast(ax, rh, rl);
    if (n >= 0) {
      return n;
    }
  } else if (ax < GMATH_CW2_LIMIT) {
    int n = reduce_fast_wide(ax, rh, rl);
    if (n >= 0) {
      return n;
    }
  }
  return reduce(ax, rh, rl);
}

/*
 * The kernel.  The reduced argument is r = h + l with 0 <= h <= pi/4 (the sign
 * of r is carried separately, see unpack_remainder) and |l| below ulp(h), or
 * l == 0 when no reduction was needed.
 *
 * Method.  Write h = a + b where a is h with all but the leading six bits of
 * its mantissa cleared: 64 slices per binade for 2^-4 <= h < 1, so a is one of
 * 256 values and 0 <= b < a/64 (b is exact, h - a).  Row k of
 * gmath_trig_rows holds sin a and cos a as double-doubles and tan a and cot a
 * as doubles, with the exact residuals d0 = sin_hi - tan_hi*cos_hi and
 * e0 = cos_hi - cot_hi*sin_hi (about 2^-54), all computed at 220 bits.  Then
 *
 *   sin(a + b + l) = sin a + cos a * (b + l) + sin a * (cos b - 1)
 *                  + cos a * (sin b - b) + ...
 *
 * and only the correction sin(a+b+l) - sin a is evaluated in double, from
 * z = b^2, ups = (b z) S(z) ~ sin b - b, cosm1 = z C(z) ~ cos b - 1, S and C
 * minimax polynomials of degree 3.  The correction is at most b/a < 1/64 (1.7%
 * for sin, 1.6% for cos, up to 3% for tan) of the result, so its rounding is
 * a few hundredths of an ulp of the result; the table value sin_hi and the
 * final addition carry the precision.  Below 2^-4 (h < 2^-4, "direct") there
 * is no table: a = 0, the row is (sin 0, cos 0) = (0, 1) and b = h.
 *
 * Why not a polynomial in r alone: over [0, pi/4] it needs its first term
 * r^3/6 in double-double (the first draft of the earlier kernel was 0.56 ulp
 * without), and tan needs degree about 15.  The table makes b < 2^-6 (or
 * < 2^-4 on the direct path), so nothing but the final add and the table value
 * needs more than 53 bits.
 *
 * Error budget (measured, not proved; the contract is 1 ulp).  The result is
 * the rounding of sin_hi + corr, which is 0.5 ulp, plus the error in corr.
 * Of corr's roundings only two are of its own size, the product cos_hi*b and
 * the sum that adds the rest to it, each at most half an ulp of a quantity
 * below 1.7% of the result, so 2 * 0.5 * 0.017 * 2 = 0.035 ulp; every other
 * term is smaller by at least b/2 < 2^-7.  The polynomial tails and the
 * rounded table lows add under 0.001 ulp.  So sin and cos stay under about
 * 0.54 ulp.  Measured (8e7 arguments against the previous double-double
 * kernel, and 480,000 oracle arguments): sin 0.5205, cos 0.5234.  tan has about
 * five roundings in its correction and one division: measured 0.5503.
 *
 * Every table entry, every polynomial coefficient and the order of every
 * operation below is fixed; the results are the same on every target.  The
 * formulas are written so that one SIMD lane can compute the same sequence
 * (the table row is one cache line; the sin and cos corrections are one
 * formula with the table columns exchanged, which an odd quadrant selects):
 * a vector kernel that follows kernel_front, kernel_tails and
 * kernel_correction operation for operation gives the same bits.
 *
 * Index range.  h <= the double nearest pi/4, which is below 2^-1 * 1.5708:
 * the largest slice index is 3 * 64 + 36 = 228, below GMATH_TRIG_ROWS, for
 * any h that reduce_any or an unreduced argument can produce (reduce_fast
 * declines above GMATH_PIO4, and reduce() returns |r| <= pi/4, which rounds
 * to at most the double GMATH_PIO4).  Rows 229 to 255 (a above pi/4) are never
 * read.  The index is masked as well, so that no h can read outside the table.
 * Tested in test_trig_kernel.cpp.
 */

#define GMATH_TRIG_DIRECT 0x1p-4
#define GMATH_TRIG_SLICE_SHIFT (52 - GMATH_TRIG_SLICE_BITS)
/* The bit pattern of 2^-4, shifted: the index of the first slice, 0. */
#define GMATH_TRIG_INDEX_BASE (0x3fb0000000000000ull >> GMATH_TRIG_SLICE_SHIFT)

/* The unit tests include this file as C++. */
#ifdef __cplusplus
#define GMATH_STATIC_ASSERT(c, m) static_assert(c, m)
#else
#define GMATH_STATIC_ASSERT(c, m) _Static_assert(c, m)
#endif

GMATH_STATIC_ASSERT(GMATH_TRIG_SIN_DEGREE == 3, "kernel_tails is written for a degree 3 sine tail");
GMATH_STATIC_ASSERT(GMATH_TRIG_COS_DEGREE == 3, "kernel_tails is written for a degree 3 cosine tail");
GMATH_STATIC_ASSERT(GMATH_TRIG_TAN_DEGREE == 6, "kernel_tan_direct is written for a degree 6 tangent tail");
GMATH_STATIC_ASSERT(GMATH_TRIG_SLICE_BITS == 6, "the table has 64 slices per binade");
GMATH_STATIC_ASSERT(GMATH_TRIG_ROWS == (4 << GMATH_TRIG_SLICE_BITS), "four binades, 2^-4 .. 1");
GMATH_STATIC_ASSERT((GMATH_TRIG_ROWS & (GMATH_TRIG_ROWS - 1)) == 0, "the slice index is masked with ROWS - 1");

/* The table row for h and b = h - a.  h >= 0. */
static inline const double * kernel_front(double h, double * b) {
  if (h < GMATH_TRIG_DIRECT) {
    *b = h;
    return gmath_trig_rows[GMATH_TRIG_ZERO_ROW];
  }
  uint64_t hb = bits_of(h);
  /* In range by the argument above; the mask makes it so by construction, so a
   * reduction that failed to bound h reads a wrong row, not memory outside the
   * table. */
  uint64_t idx = ((hb >> GMATH_TRIG_SLICE_SHIFT) - GMATH_TRIG_INDEX_BASE) & (GMATH_TRIG_ROWS - 1);
  *b = h - double_of(hb & ~((1ull << GMATH_TRIG_SLICE_SHIFT) - 1));
  return gmath_trig_rows[idx];
}

/* ups ~ sin b - b and cosm1 ~ cos b - 1 for 0 <= b < 2^-4, by Horner in z. */
static inline void kernel_tails(double b, double * ups, double * cosm1) {
  const double * s = gmath_trig_sin_tail;
  const double * c = gmath_trig_cos_tail;
  double z = b * b;
  double u = b * z;
  *ups = u * (((s[3] * z + s[2]) * z + s[1]) * z + s[0]);
  *cosm1 = z * (((c[3] * z + c[2]) * z + c[1]) * z + c[0]);
}

/* f(a + b + l) - ph for f = sin with (ph, pl, qh, ql) = (sin a, cos a) as
 * double-doubles, and for f = cos with (cos a, -sin a): the one formula, the
 * columns exchanged.  qh and ql are negated exactly for cos, so every
 * product and sum is the same IEEE operation on the same operands as the
 * written-out cosine formula. */
static inline double kernel_correction(double ph, double pl, double qh, double ql, double b, double l, double ups,
    double cosm1) {
  double r = ((pl + qh * l) + qh * ups) + (ph * cosm1 + ql * b);
  return qh * b + r;
}

/* sin(h + l), h >= 0, as a double. */
static inline double kernel_sin(double h, double l) {
  double b, ups, cosm1;
  const double * e = kernel_front(h, &b);
  kernel_tails(b, &ups, &cosm1);
  double corr = kernel_correction(e[GMATH_TRIG_SIN_HI], e[GMATH_TRIG_SIN_LO], e[GMATH_TRIG_COS_HI],
      e[GMATH_TRIG_COS_LO], b, l, ups, cosm1);
  return e[GMATH_TRIG_SIN_HI] + corr;
}

/* cos(h + l), h >= 0, as a double. */
static inline double kernel_cos(double h, double l) {
  double b, ups, cosm1;
  const double * e = kernel_front(h, &b);
  kernel_tails(b, &ups, &cosm1);
  double corr = kernel_correction(e[GMATH_TRIG_COS_HI], e[GMATH_TRIG_COS_LO], -e[GMATH_TRIG_SIN_HI],
      -e[GMATH_TRIG_SIN_LO], b, l, ups, cosm1);
  return e[GMATH_TRIG_COS_HI] + corr;
}

/* tan(h + l) (odd == 0) or cot(h + l) (odd != 0) for h < 2^-4, no table:
 * tan r = r + r z T(z).  The cotangent is the reciprocal of a double-double
 * sum, refined once. */
static double kernel_tan_direct(double h, double l, int odd) {
  const double * t = gmath_trig_tan_tail;
  double z = h * h;
  double poly = t[6];
  for (int i = 5; i >= 0; i--) {
    poly = poly * z + t[i];
  }
  double rest = l + (h * z) * poly;
  if (!odd) {
    return h + rest;
  }
  gmath_dd td = fast_two_sum(h, rest);
  double q1 = 1.0 / td.hi;
  gmath_dd p = two_prod(q1, td.hi);
  double rem = ((1.0 - p.hi) - p.lo) - q1 * td.lo;
  return q1 + rem * q1;
}

/* tan(h + l) (odd == 0) or cot(h + l) (odd != 0), h >= 0:
 *   tan(a+b+l) = tan a + ((cs - tan a * cc) + d0) / (cos_hi + cc)
 * with cs = sin(a+b+l) - sin_hi and cc = cos(a+b+l) - cos_hi the two
 * corrections and d0 = sin_hi - tan a * cos_hi from the table; cot is the
 * same with the roles of sin and cos exchanged.  The division is of a
 * quantity below 3% of the result. */
static inline double kernel_tan(double h, double l, int odd) {
  if (h < GMATH_TRIG_DIRECT) {
    return kernel_tan_direct(h, l, odd);
  }
  double b, ups, cosm1;
  const double * e = kernel_front(h, &b);
  kernel_tails(b, &ups, &cosm1);
  double sh = e[GMATH_TRIG_SIN_HI];
  double ch = e[GMATH_TRIG_COS_HI];
  double cs = kernel_correction(sh, e[GMATH_TRIG_SIN_LO], ch, e[GMATH_TRIG_COS_LO], b, l, ups, cosm1);
  double cc = kernel_correction(ch, e[GMATH_TRIG_COS_LO], -sh, -e[GMATH_TRIG_SIN_LO], b, l, ups, cosm1);
  if (!odd) {
    double th = e[GMATH_TRIG_TAN_HI];
    return th + ((cs - th * cc) + e[GMATH_TRIG_TAN_D0]) / (ch + cc);
  }
  double kh = e[GMATH_TRIG_COT_HI];
  return kh + ((cc - kh * cs) + e[GMATH_TRIG_COT_E0]) / (sh + cs);
}

static double quiet_nan(double x) {
  /* sin(+-inf) is invalid by Annex F, and a signalling NaN raises it too:
   * x - x does both.  The value returned is the same on every target. */
  volatile double t = x - x;
  (void)t;
  return double_of(QNAN_BITS);
}

static double apply_sign(double r, uint64_t sign) {
  return double_of(bits_of(r) ^ sign);
}

/* The reduced argument rh + rl (from reduce_any, or ax itself and 0 when no
 * reduction was needed) as h = |rh|, l = rl with the sign of rh removed, and
 * *rs the sign bit of rh.  The kernels see only h >= 0; the sign of r reappears
 * in the result of the odd functions. */
static inline void unpack_remainder(double rh, double rl, double * h, double * l, uint64_t * rs) {
  *rs = bits_of(rh) & SIGN_BIT;
  *h = double_of(bits_of(rh) & ABS_MASK);
  *l = double_of(bits_of(rl) ^ *rs);
}

double gmath_sin(double x) {
  uint64_t sign = bits_of(x) & SIGN_BIT;
  double ax = double_of(bits_of(x) & ABS_MASK);
  if (bits_of(ax) >= INF_BITS) {
    return quiet_nan(x);
  }
  if (ax < 0x1p-28) {
    return x;
  }
  double rh = ax, rl = 0.0, h, l;
  uint64_t rs;
  int n = 0;
  if (ax > GMATH_PIO4) {
    n = reduce_any(ax, &rh, &rl);
  }
  unpack_remainder(rh, rl, &h, &l, &rs);
  /* Even quadrants sin r (odd in r), odd ones cos r (even in r); n = 2, 3 negate. */
  double r = (n & 1) ? kernel_cos(h, l) : kernel_sin(h, l);
  uint64_t sg = (n & 1) ? 0 : rs;
  return apply_sign(r, (n & 2) ? sign ^ sg ^ SIGN_BIT : sign ^ sg);
}

double gmath_cos(double x) {
  double ax = double_of(bits_of(x) & ABS_MASK);
  if (bits_of(ax) >= INF_BITS) {
    return quiet_nan(x);
  }
  if (ax < 0x1p-27) {
    return 1.0;
  }
  double rh = ax, rl = 0.0, h, l;
  uint64_t rs;
  int n = 0;
  if (ax > GMATH_PIO4) {
    n = reduce_any(ax, &rh, &rl);
  }
  unpack_remainder(rh, rl, &h, &l, &rs);
  /* cos: n = 0 cos r, 1 -sin r, 2 -cos r, 3 sin r. */
  double r = (n & 1) ? kernel_sin(h, l) : kernel_cos(h, l);
  uint64_t sg = (n & 1) ? rs : 0;
  return apply_sign(r, ((n + 1) & 2) ? sg ^ SIGN_BIT : sg);
}

double gmath_tan(double x) {
  uint64_t sign = bits_of(x) & SIGN_BIT;
  double ax = double_of(bits_of(x) & ABS_MASK);
  if (bits_of(ax) >= INF_BITS) {
    return quiet_nan(x);
  }
  if (ax < 0x1p-28) {
    return x;
  }
  double rh = ax, rl = 0.0, h, l;
  uint64_t rs;
  int n = 0;
  if (ax > GMATH_PIO4) {
    n = reduce_any(ax, &rh, &rl);
  }
  unpack_remainder(rh, rl, &h, &l, &rs);
  /* tan x = tan r for even n, -cot r for odd n. */
  double t = kernel_tan(h, l, n & 1);
  return apply_sign(t, (n & 1) ? sign ^ rs ^ SIGN_BIT : sign ^ rs);
}
