/* The low 26 stored bits of m are cleared to make its high part: 27 significant
 * bits, which times a 26-bit multiplier c is an exact product. */
#define GMATH_LOG_LOW_MASK 0x3ffffffull
/* The low 27 stored bits cleared leave 26 significant bits: a number whose square is an exact product. */
#define GMATH_LOG_SPLIT_MASK 0x7ffffffull

GMATH_STATIC_ASSERT(GMATH_LOG_ROW_BITS == 7, "the row index is the top seven bits of the offset pattern");

/* The front end shared by log and pow's double-double log: x = 2^e m, the row
 * of m, and z = zh + zl = c m - 1 exactly (up to the last bit of zl).
 * x must be a positive finite normal double. */
static inline const double * log_front(uint64_t xb, int * e, double * zh, double * zl) {
  uint64_t tmp = xb - GMATH_LOG_OFF;
  int64_t ei = (int64_t)tmp >> 52;
  uint64_t j = (tmp >> (52 - GMATH_LOG_ROW_BITS)) & ((1u << GMATH_LOG_ROW_BITS) - 1u);
  uint64_t mb = xb - ((uint64_t)ei << 52);
  const double * row = gmath_log_rows[j];
  double m = gmath_double(mb);
  double mh = gmath_double(mb & ~GMATH_LOG_LOW_MASK);
  double ml = m - mh;
  double c = row[0];
  double t1 = mh * c - 1.0;
  double t2 = ml * c;
  double s = t1 + t2;
  *zh = s;
  *zl = t2 - (s - t1);
  *e = (int)ei;
  return row;
}

/* x = 2^e m (see log_front); the subnormals are scaled by 2^52 first. */
static inline uint64_t log_normalize(uint64_t xb, int * adj) {
  *adj = 0;
  if (xb < 0x0010000000000000ull) {
    /* a positive subnormal (zero is handled by the callers) */
    xb = gmath_bits(gmath_double(xb) * 0x1p52);
    *adj = -52;
  }
  return xb;
}

/*
 * log x = e ln2 + t + log1p z, x = 2^e m, z = c m - 1 (see log_front).
 *
 *   A    = e ln2_hi + t_hi          exact: ln2_hi has 41 bits, t_hi is a multiple of 2^-41, |e| < 2^11
 *   (s, c1) = FastTwoSum(A, zh)     s + c1 = A + zh exactly (|A| >= |zh| unless A = 0)
 *   q    = z^2 P(z)                 log1p z - z, P of degree 5 fitted to be accurate relative to z
 *   tail = (e ln2_lo + t_lo + zl) + c1 + q
 *   log x = s + tail                the only rounding of the size of the result
 *
 * Error budget (measured, not proved; the contract is 1 ulp): the last addition is 0.5 ulp. Everything
 * else is in the tail, which is at most 2^-7 of the result unless A = 0, where the result is z + q
 * and q is at most 2^-8 z: its roundings are 2^-53 of that (below 2^-60 of the result), the
 * polynomial is accurate to 2^-60.4 of z, and zh + zl is c m - 1 to 2^-106.  The worst result is
 * therefore within about 0.502 ulp (0.5048 over the corpus, which holds inputs chosen to expose a
 * coefficient).  The rows around 1 have c = 1, so x near 1 loses nothing to cancellation.
 */
double gmath_log(double x) {
  uint64_t xb = gmath_bits(x);
  int adj = 0;
  if (xb - 0x0010000000000000ull >= GMATH_INF_BITS - 0x0010000000000000ull) {
    /* not a positive normal finite number */
    if ((xb & GMATH_ABS_MASK) > GMATH_INF_BITS) {
      return gmath_nan_of(x);
    }
    if ((xb & GMATH_ABS_MASK) == 0) {
      return gmath_div_by_zero(GMATH_SIGN_BIT);
    }
    if (xb & GMATH_SIGN_BIT) {
      return gmath_invalid();
    }
    if (xb == GMATH_INF_BITS) {
      return x;
    }
    xb = log_normalize(xb, &adj);
  }
  int e;
  double zh, zl;
  const double * row = log_front(xb, &e, &zh, &zl);
  e += adj;
  const double * p = gmath_log_poly;
  double z2 = zh * zh;
  double z4 = z2 * z2;
  double q = z2 * (((p[0] + p[1] * zh) + (p[2] + p[3] * zh) * z2) + (p[4] + p[5] * zh) * z4);
  double ed = gmath_small_int(e);
  double a = ed * GMATH_LN2_HI + row[1];
  gmath_pair sc = gmath_fast_two_sum(a, zh);
  double tail = ((ed * GMATH_LN2_LO + row[2]) + zl) + sc.lo;
  return sc.hi + (tail + q);
}

/*
 * log of a positive finite double as a double-double hi + lo for pow, accurate to
 * 2^-67 of the value (not normalized: |lo| is at most 2^-12 |hi|, the cubic term).
 *
 *   log x = A + zh - zh^2/2 + zh^3 R(zh) + (t_lo + e ln2_lo + zl (1 - zh))
 *
 * with A = e ln2_hi + t_hi exact and z = zh + zl (the derivative of z - z^2/2 carries zl: without
 * the factor 1 - zh the error is zh zl, up to 2^-61 of |log x| in the rows next to the ones with
 * c = 1: 0.05 ulp of pow at the largest results).  z^2 is taken as a double-double (its
 * rounding error, 2^-53 z^2/2, would be as large as 2^-60 |log x| for the rows
 * around 1); the cubic term is a double: its own rounding is 2^-53 z^3/3, below
 * 2^-70 |log x|, and R is fitted to 2^-69.5 relative to z.  The sums are Knuth's
 * FastTwoSum: |A| >= |z| unless A = 0, where the sum is exact (fit_explog.py
 * checks the table for that).  The product y log x of the caller multiplies this
 * error by |y log x| <= 746, so its share of the error of pow is at most
 * 746 * 2^-67 = 2^-57.5 (0.02 ulp), at the largest results.
 */
static inline gmath_pair log_dd_parts(uint64_t xb, int adj) {
  int e;
  double zh, zl;
  const double * row = log_front(xb, &e, &zh, &zl);
  e += adj;
  const double * p = gmath_log_dd_poly;
  /* z^2 as p1 + p2: zh = zhh + zhl with zhh of 26 bits, so zhh^2 (p1) is exact, 2 zhh zhl is exact,
   * and zhl^2 is below 2^-52 z^2 (its rounding is of no consequence). */
  double zhh = gmath_double(gmath_bits(zh) & ~GMATH_LOG_SPLIT_MASK);
  double zhl = zh - zhh;
  double p1 = zhh * zhh;
  double p2 = 2.0 * (zhh * zhl) + zhl * zhl;
  double z2 = zh * zh;
  double z4 = z2 * z2;
  double poly = ((p[0] + p[1] * zh) + (p[2] + p[3] * zh) * z2) + ((p[4] + p[5] * zh) + p[6] * z2) * z4;
  double t = (zh * z2) * poly;
  double ed = gmath_small_int(e);
  double a = ed * GMATH_LN2_HI + row[1];
  gmath_pair s1 = gmath_fast_two_sum(a, zh);
  gmath_pair s2 = gmath_fast_two_sum(s1.hi, -0.5 * p1);
  gmath_pair r;
  r.hi = s2.hi;
  r.lo = (s1.lo + s2.lo) + (((t - 0.5 * p2) + (zl - zh * zl)) + (ed * GMATH_LN2_LO + row[2]));
  return r;
}

static inline gmath_pair log_dd(double x) {
  uint64_t xb = gmath_bits(x);
  int adj = 0;
  if (xb < 0x0010000000000000ull) {
    xb = log_normalize(xb, &adj);
  }
  return log_dd_parts(xb, adj);
}

/* Normalize the logarithm's pair before multiplication. Its relative kernel
 * error is about 2^-67; error-free normalization and the exact high product
 * retain that reserve until the final rounding. Products involving a low
 * part are at most 2^-53 of the answer, so their roundoff is about 2^-106.
 * Simply multiplying gmath_log(x) by one rounded reciprocal would lose this
 * reserve. No existing log/pow expression order changes. */
static inline double logbase_positive(double x, double ih, double il) {
  uint64_t xb = gmath_bits(x);
  int adj = 0;
  if (xb < 0x0010000000000000ull) {
    /* Match log_normalize(x * 2^52) in bits. A compiler may speculate that
     * multiplication on normal inputs when exceptions are not observable to
     * its optimizer, spuriously overflowing huge inputs (seen with Clang).
     * Integer normalization gives the identical kernel arguments safely. */
    unsigned shift = 0;
    while (xb < 0x0010000000000000ull) {
      xb <<= 1;
      ++shift;
    }
    xb = ((uint64_t)(53u - shift) << 52) | (xb & 0x000fffffffffffffull);
    adj = -52;
  }
  gmath_pair l = log_dd_parts(xb, adj);
  l = gmath_fast_two_sum(l.hi, l.lo);
  gmath_pair p = gmath_two_prod(l.hi, ih);
  double cross = l.hi * il + l.lo * il;
  double tail = (p.lo + l.lo * ih) + cross;
  return p.hi + tail;
}

/* A power of two's logarithm is an integer and needs no inexact arithmetic,
 * including the 52 subnormal binary powers. Called only for a positive finite
 * value; a non-power returns zero through the separate found flag. */
static inline double log2_binary_power(uint64_t xb, int * found) {
  const uint64_t fraction = 0x000fffffffffffffull;
  *found = 1;
  if (xb >= 0x0010000000000000ull) {
    if ((xb & fraction) == 0) {
      return gmath_small_int((int)(xb >> 52) - 1023);
    }
  }
  else if ((xb & (xb - 1)) == 0) {
    int e = -1074;
    while ((xb >>= 1) != 0) {
      ++e;
    }
    return gmath_small_int(e);
  }
  *found = 0;
  return 0.0;
}

/* A binary32 input has only 24 significand bits, so m times the table's
 * 26-bit multiplier is exact in double; z = c*m - 1 is exact by Sterbenz.
 * The existing table bounds |z| below about 0.008. The five-term log1p
 * series has remainder at most |z|^6 / (6*(1-|z|)), ample reserve for a
 * one-ulp binary32 result. The rows touching one have c=1 and t=0, keeping
 * relative accuracy when the final logarithm is tiny. Computing e directly
 * in base two avoids a high-precision natural-log conversion on this path. */
static inline double log2f_positive(double x) {
  uint64_t xb = gmath_bits(x);
  int found;
  double exact = log2_binary_power(xb, &found);
  if (found) {
    return exact;
  }
  uint64_t tmp = xb - GMATH_LOG_OFF;
  int64_t e = (int64_t)tmp >> 52;
  unsigned j = (unsigned)((tmp >> (52 - GMATH_LOG_ROW_BITS)) &
      ((1u << GMATH_LOG_ROW_BITS) - 1u));
  double m = gmath_double(xb - ((uint64_t)e << 52));
  const double * row = gmath_log_rows[j];
  double z = m * row[0] - 1.0;
  double p = z + (z * z) * (-0.5 + z *
      (0x1.5555555555555p-2 + z * (-0.25 + z * 0x1.999999999999ap-3)));
  double logm = (row[1] + row[2]) + p;
  return gmath_small_int((int)e) + logm * GMATH_LOG2_INV_HI;
}

/* Called only for zeros, negatives, infinities and NaNs, with the same
 * special-value rules as log. Positive finite inputs stay in the callers. */
static inline double logbase_special(double x, uint64_t xb) {
  uint64_t ax = xb & GMATH_ABS_MASK;
  if (ax > GMATH_INF_BITS) {
    return gmath_nan_of(x);
  }
  if (ax == 0) {
    return gmath_div_by_zero(GMATH_SIGN_BIT);
  }
  if (xb & GMATH_SIGN_BIT) {
    return gmath_invalid();
  }
  return x; /* +infinity */
}

double gmath_log2(double x) {
  uint64_t xb = gmath_bits(x);
  if (xb == 0 || xb >= GMATH_INF_BITS) {
    return logbase_special(x, xb);
  }
  int found;
  double exact = log2_binary_power(xb, &found);
  if (found) {
    return exact;
  }
  return logbase_positive(x, GMATH_LOG2_INV_HI, GMATH_LOG2_INV_LO);
}

double gmath_log10(double x) {
  uint64_t xb = gmath_bits(x);
  if (xb == 0 || xb >= GMATH_INF_BITS) {
    return logbase_special(x, xb);
  }
  if (xb == 0x3ff0000000000000ull) {
    return 0.0;
  }
  return logbase_positive(x, GMATH_LOG10_INV_HI, GMATH_LOG10_INV_LO);
}

float gmath_log2f(float x) {
  uint32_t xb;
  memcpy(&xb, &x, sizeof xb);
  uint32_t ax = xb & 0x7fffffffu;
  uint32_t result;
  if (ax > 0x7f800000u) {
    if ((ax & 0x00400000u) == 0) {
      (void)gmath_invalid();
    }
    result = 0x7fc00000u;
  }
  else if (ax == 0) {
    (void)gmath_div_by_zero(GMATH_SIGN_BIT);
    result = 0xff800000u;
  }
  else if (xb & 0x80000000u) {
    (void)gmath_invalid();
    result = 0x7fc00000u;
  }
  else if (ax == 0x7f800000u) {
    return x;
  }
  else {
    /* Widening is exact; all nonzero finite log2f results are normal. */
    return (float)log2f_positive((double)x);
  }
  float r;
  memcpy(&r, &result, sizeof r);
  return r;
}

