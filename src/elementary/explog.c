/* 0 if y (finite, nonzero) is not an integer, 1 if an odd integer, 2 if even. */
static int integer_class(uint64_t ay) {
  int e = (int)(ay >> 52);
  if (e < 1023) {
    return 0;
  }
  if (e >= 1023 + 53) {
    return 2;
  }
  uint64_t m = (ay & 0xfffffffffffffull) | 0x10000000000000ull;
  int sh = 1023 + 52 - e;
  if (m & ((1ull << sh) - 1)) {
    return 0;
  }
  return ((m >> sh) & 1) ? 1 : 2;
}

/* y * l as a double-double, for |y| < 2^64 and |l| < 746: Dekker's product with the halves cut by
 * masking (26 and 27 bits), so that three of the four partial products are exact and the fourth
 * (27 by 27 bits) is below 2^-52 of the product. */
static inline gmath_pair pow_product(double y, double l) {
  gmath_pair r;
  double p = y * l;
  double yh = gmath_double(gmath_bits(y) & ~GMATH_LOG_SPLIT_MASK);
  double lh = gmath_double(gmath_bits(l) & ~GMATH_LOG_SPLIT_MASK);
  double yl = y - yh;
  double ll = l - lh;
  r.hi = p;
  r.lo = (((yh * lh - p) + yh * ll) + yl * lh) + yl * ll;
  return r;
}

/* The part of pow that follows the special values: x finite and positive; y finite and nonzero
 * with |y| < 2^64.  rsign is the sign bit of the result. */
static inline double pow_main(double x, double y, uint64_t rsign) {
  gmath_pair lg = log_dd(x);
  gmath_pair w = pow_product(y, lg.hi);
  double wl = w.lo + y * lg.lo;
  uint64_t wa = gmath_bits(w.hi) & GMATH_ABS_MASK;
  int k;
  if (wa - gmath_bits(GMATH_EXP_TINY) >= gmath_bits(GMATH_EXP_FAST_LIMIT) - gmath_bits(GMATH_EXP_TINY)) {
    /* |w| below 2^-54, or 708 and above (or NaN, which cannot happen) */
    if (w.hi > GMATH_EXP_CERTAIN_OVER) {
      return gmath_overflow(rsign);
    }
    if (w.hi < GMATH_EXP_CERTAIN_UNDER) {
      return gmath_underflow(rsign);
    }
    if (wa < gmath_bits(GMATH_EXP_TINY)) {
      return gmath_double(gmath_bits(1.0 + w.hi) | rsign);
    }
    double r = exp_core(w.hi, wl, 1, &k);
    return gmath_double(gmath_bits(scale_slow(r, k)) | rsign);
  }
  double r = exp_core(w.hi, wl, 1, &k);
  return gmath_double(gmath_bits(r * gmath_double((uint64_t)(k + 1023) << 52)) | rsign);
}

/*
 * pow(x, y) = exp(y log x) for x > 0 (a negative x with an integer y uses |x| and the parity of y).
 *
 *   (lh, ll) = log x                  log_dd: a double-double accurate to 2^-67
 *   (wh, wl) = y (lh + ll)            pow_product: y lh exactly, plus y ll rounded
 *   exp(wh + wl)                      exp_core, which takes n from wh + wl and r from both parts
 *
 * Error budget (measured, not proved; the contract is 1 ulp): the final addition in exp_core is 0.5
 * ulp.  The error of log_dd, 2^-67 of log x, becomes at most 746 * 2^-67 = 2^-57.5 of the result when
 * |y log x| is as large as it gets; y ll is rounded, at most 0.02 of w at its largest, another 2^-58;
 * exp_core adds 2^-61.  So the worst is about 0.5 plus 0.02 ulp, for x close to 1 and a huge y
 * (measured 0.5084 over the corpus and 0.5077 over 1.2e6 random arguments; the first version, which
 * left zl (1 - zh) out of log_dd, measured 0.549).  A result that is exactly representable is
 * returned exactly: the neighbours are at least half an ulp away and the error before the last
 * addition is under 2^-56.  A result in the subnormal range is rounded twice (exp_core to 53 bits,
 * the scaling to the subnormal grid): at most 0.75 ulp.
 * C99 Annex F.9.4.4 is the ladder below the common case.
 */
double gmath_pow(double x, double y) {
  uint64_t xb = gmath_bits(x);
  uint64_t yb = gmath_bits(y);
  const uint64_t one = 0x3ff0000000000000ull;
  uint64_t ay = yb & GMATH_ABS_MASK;

  /* The common case: a positive normal x and a y of ordinary size (x = 1 is in it: its logarithm
   * is 0 and the result 1). */
  if (xb - 0x0010000000000000ull < GMATH_INF_BITS - 0x0010000000000000ull &&
      ay - gmath_bits(0x1p-60) < gmath_bits(0x1p64) - gmath_bits(0x1p-60)) {
    return pow_main(x, y, 0);
  }
  uint64_t ax = xb & GMATH_ABS_MASK;

  /* The values that do not depend on the other argument being a number. */
  if (ay == 0 || xb == one) {
    return 1.0;
  }
  if (ax > GMATH_INF_BITS || ay > GMATH_INF_BITS) {
    return gmath_nan_of(ax > GMATH_INF_BITS ? x : y);
  }
  uint64_t ysign = yb & GMATH_SIGN_BIT;
  uint64_t xsign = xb & GMATH_SIGN_BIT;
  if (ay == GMATH_INF_BITS) {
    if (ax == one) {
      return 1.0; /* pow(-1, +-inf) */
    }
    int below = ax < one;
    if (!ysign) {
      return below ? 0.0 : gmath_double(GMATH_INF_BITS);
    }
    if (below) {
      return ax == 0 ? gmath_div_by_zero(0) : gmath_double(GMATH_INF_BITS);
    }
    return 0.0;
  }
  int yc = integer_class(ay);
  /* arithmetic, not a conditional: a compiler told -fno-signed-zeros may merge a choice between
   * the constants -0.0 and +0.0 into +0.0, and the sign of the zero results below is the contract */
  uint64_t rsign = xsign & (0 - (uint64_t)(yc == 1));
  if (ax == GMATH_INF_BITS) {
    if (!ysign) {
      return gmath_double(GMATH_INF_BITS | rsign);
    }
    return gmath_double(rsign);
  }
  if (ax == 0) {
    if (ysign) {
      return gmath_div_by_zero(rsign);
    }
    return gmath_double(rsign);
  }
  if (xsign && yc == 0) {
    return gmath_invalid();
  }
  if (ax == one) {
    return gmath_double(one | rsign); /* pow(-1, finite y) */
  }

  /* x finite, nonzero, not +-1; y finite, nonzero.  |log x| is at least 2^-53, so a y of 2^64 or
   * more overflows or underflows whatever else is true, by the sign of log x (x > 1) and of y. */
  if (ay >= gmath_bits(0x1p64)) {
    return ((ax > one) == (ysign == 0)) ? gmath_overflow(rsign) : gmath_underflow(rsign);
  }
  return pow_main(gmath_double(ax), y, rsign);
}
