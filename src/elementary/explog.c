/**
 * @file
 *
 * gmath_exp, gmath_log and gmath_pow.
 *
 * Written from the published algorithms, not from any library's source:
 *
 *   - exp: Tang's table-driven method (Tang, "Table-driven implementation of
 *     the exponential function in IEEE floating-point arithmetic", 1989;
 *     Muller, Elementary Functions, chapter 5 and 6).  x = n ln2/128 + r with
 *     |r| <= ln2/256, exp x = 2^(n div 128) * 2^((n mod 128)/128) * exp r: the
 *     128 values 2^(j/128) are a table of double-doubles, exp r is a short
 *     minimax polynomial.  ln2/128 is split in two parts, the first short
 *     enough that n times it is exact, so r is the exact remainder up to one
 *     rounding.
 *   - log: Tang's table-driven logarithm (Tang, "Table-driven implementation
 *     of the logarithm function in IEEE floating-point arithmetic", 1990;
 *     Muller, chapter 5).  x = 2^e m with m in [0.707, 1.414); a table row
 *     chosen by the leading bits of m holds a short multiplier c with c m
 *     close to 1, so z = c m - 1 is small and computed exactly (in two parts,
 *     by splitting m) and log m = -log c + log1p z, log1p z a short
 *     polynomial.  The two rows around 1 have c = 1, so that log x for x near
 *     1 is the polynomial of z = x - 1, exact, and no cancellation occurs.
 *   - pow: exp(y log x), with log x as a double-double accurate to about
 *     2^-68, the product y log x as a double-double and exp of a double-double
 *     argument (Muller, chapter 7).  The special cases are C99 Annex F.9.4.4.
 *
 * Error-free transformations (Knuth's TwoSum, Dekker's split and product) are
 * from elem_common.h.  The table and the polynomials are generated by
 * tools/oracle/fit_explog.py and held in explog_tables.h.
 *
 * Nothing here calls libm or uses a fused multiply-add. Intermediates remain
 * in binary64; log2f narrows only at its final return. Every double expression
 * has an explicit operation order, and the library uses -ffp-contract=off.
 */

#include <ghoti.io/math/macros.h>

#include <ghoti.io/math/elementary.h>

#include <float.h>

#include "elem_common.h"
#include "explog_tables.h"
