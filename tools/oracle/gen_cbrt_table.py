"""Generate midpoint cube-root seeds from independent MPFR/mpmath arithmetic.

--out is a full header path; without it, write the deterministic header to stdout.
Run inside the pinned oracle image. No third-party coefficients are used.
"""
import argparse
from fractions import Fraction
import math
from pathlib import Path
import struct
import sys

import gmpy2
from mpmath import mp
from fitlib import HEADER


def bits(x):
    return struct.unpack('>Q', struct.pack('>d', x))[0]


def mp_fraction(x):
    mantissa, exponent = mp.frexp(x)
    significant = int(mp.ldexp(mantissa, mp.prec))
    return Fraction(significant) * Fraction(2) ** (int(exponent) - mp.prec)


def check_round(reference, independent, name):
    n, d = reference.as_integer_ratio()
    fr = Fraction(int(n), int(d))
    other = mp_fraction(independent)
    if abs(fr - other) > abs(fr) * Fraction(2) ** -400:
        raise RuntimeError('MPFR/mpmath disagree for cbrt table ' + name)
    result = float(fr)
    if bits(result) != bits(float(other)):
        raise RuntimeError('MPFR/mpmath rounded values disagree for cbrt table ' + name)
    return result


def certify_root(exact_input, result):
    """Exact midpoint-cube certificate for the rounded seed/factor root."""
    root = Fraction.from_float(result)
    low = (Fraction.from_float(math.nextafter(result, -math.inf)) + root) / 2
    high = (Fraction.from_float(math.nextafter(result, math.inf)) + root) / 2
    lo_cube, hi_cube = low ** 3, high ** 3
    if (exact_input < lo_cube or exact_input > hi_cube or
            ((exact_input == lo_cube or exact_input == hi_cube) and bits(result) & 1)):
        raise RuntimeError('cbrt table exact nearest-root certificate failed')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    mp.prec = 640
    rows, factors = [], []
    with gmpy2.context(precision=600, round=gmpy2.RoundToNearest):
        for j in range(64):
            midpoint = Fraction(129 + 2 * j, 128)
            m = gmpy2.mpfr(midpoint.numerator) / midpoint.denominator
            independent = mp.mpf(midpoint.numerator) / midpoint.denominator
            reciprocal = check_round(1 / m, 1 / independent, 'reciprocal[%d]' % j)
            root = check_round(gmpy2.cbrt(m), mp.root(independent, 3), 'root[%d]' % j)
            certify_root(midpoint, root)
            if bits(reciprocal) != bits(float(1 / midpoint)):
                raise RuntimeError('cbrt reciprocal fails independent rational rounding')
            rows.append((reciprocal, root))
        for r in range(3):
            power = 1 << r
            factor = check_round(gmpy2.cbrt(gmpy2.mpfr(power)),
                                 mp.root(power, 3), 'factor[%d]' % r)
            certify_root(Fraction(power), factor)
            factors.append(factor)
        for x, expected in ((1, 1.0), (8, 2.0), (27, 3.0)):
            got = check_round(gmpy2.cbrt(gmpy2.mpfr(x)), mp.root(x, 3), 'self-check')
            if bits(got) != bits(expected):
                raise RuntimeError('cbrt table generator self-check failed')
    out = [HEADER, '''/**
 * @file
 * Private midpoint seeds generated by tools/oracle/gen_cbrt_table.py in the
 * pinned oracle image. Regenerate; do not edit. Each binary64 constant is
 * independently rounded from MPFR at 600 bits and mpmath at 640 bits.
 * Row j uses the exact midpoint m_j = 1 + (2*j + 1)*2^-7.
 */
#ifndef GHOTI_IO_GMATH_SRC_ELEMENTARY_CBRT_TABLE_H
#define GHOTI_IO_GMATH_SRC_ELEMENTARY_CBRT_TABLE_H

#include <ghoti.io/math/macros.h>

#define GMATH_CBRT_TABLE_BITS 6

/* Each row is {1/m_j, cbrt(m_j)}. */
static const double gmath_cbrt_seed[64][2] = {''']
    for j, (reciprocal, root) in enumerate(rows):
        out.append('  /* %2d */ {%s, %s},' % (j, reciprocal.hex(), root.hex()))
    out += ['};', '', '/* cbrt(2^r), r = 0, 1, 2. */',
            'static const double gmath_cbrt_factor[3] = {%s};' %
            ', '.join(x.hex() for x in factors), '',
            '#endif /* GHOTI_IO_GMATH_SRC_ELEMENTARY_CBRT_TABLE_H */']
    text = '\n'.join(out) + '\n'
    if args.out is None:
        sys.stdout.write(text)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
        print('cbrt table: 64 reciprocal/root rows and 3 factors', flush=True)


if __name__ == '__main__':
    main()
