"""Compute the starting table of the reciprocal square root (gmath_sqrt's portable method; it was hypot's) and print
src/elementary/hypot_table.h.

Runs in the pinned oracle image (tools/oracle/oracle.py fit-hypot, `make
oracle-fit`), at 240 bits.  The method is Newton's iteration for 1/sqrt(s) from
a tabulated start (Muller, Elementary Functions, chapter 5).  Row i holds, for
the number s = 2^(E - 1023) (1 + f) of which i is the nine leading bits after
the sign (the low bit of the biased exponent E, then the top eight bits of the
mantissa f), the starting value of 1/sqrt(s) for E = 1023 (i < 256: an odd
exponent after the bias, so s in [2, 4)) or E = 1024 (i >= 256: s in [1, 2)),
scaled in hypot.c by 2^-floor((E - 1023)/2).  A cell is one 2^-8 of the
mantissa wide, and the table value is half way between the values of 1/sqrt
at its two ends, so that the start is within 2^-10 of 1/sqrt(s) (the script
asserts 2^-9.9); two Newton steps give 2^-38 relative.
"""

import sys

from fitlib import HEADER, hexd, mp, mpf

sys.stderr.write("fit_hypot.py, mpmath at %d bits\n" % mp.prec)

ROW_BITS = 9


def main():
    rows = []
    worst = mpf(0)
    for i in range(1 << ROW_BITS):
        p = i >> 8  # the low bit of the biased exponent
        j = i & 255
        q = 1 if p == 0 else 0  # E - 1023 = 2h + q
        lo = mpf(2) ** q * (1 + mpf(j) / 256)
        hi = mpf(2) ** q * (1 + mpf(j + 1) / 256)
        t = (1 / mp.sqrt(lo) + 1 / mp.sqrt(hi)) / 2
        rows.append(float(t))
        for e in (lo, hi):
            worst = max(worst, abs(mpf(float(t)) * mp.sqrt(e) - 1))
    sys.stderr.write("start: worst relative error over the cells 2^%.2f\n" % float(mp.log(worst, 2)))
    assert worst < mpf(2) ** -9.9
    out = []
    w = out.append
    w(HEADER)
    w("""/*
 * GENERATED by tools/oracle/fit_hypot.py in the pinned oracle image
 * (`make oracle-fit`).  Do not edit; regenerate.  Regenerating can change
 * the results, and so tests/corpus/trig.hash.  The method is described in the
 * comment above gmath_sqrt_estimate in sqrt_impl.h (the table was hypot's until story 4a; hypot now calls gmath_sqrt).
 */

#ifndef GHOTI_IO_GMATH_HYPOT_TABLE_H
#define GHOTI_IO_GMATH_HYPOT_TABLE_H

#include <ghoti.io/math/macros.h>

#include "elem_common.h"

#define GMATH_HYPOT_ROW_BITS %d

/* The start of 1/sqrt(s); row i = (low bit of the biased exponent) << 8 | (top eight mantissa bits). */
GMATH_ALIGN16 static const double gmath_hypot_rsqrt[1 << GMATH_HYPOT_ROW_BITS] = {""" % ROW_BITS)
    for i in range(0, len(rows), 4):
        w("  " + ", ".join(hexd(v) for v in rows[i:i + 4]) + ",")
    w("};")
    w("")
    w("#endif /* GHOTI_IO_GMATH_HYPOT_TABLE_H */")
    sys.stdout.write("\n".join(out) + "\n")


main()
