"""Generate double-double inverse logarithms in the pinned oracle image.

mpmath computes each split at 240 bits; independent MPFR arithmetic checks
its relative reconstruction error before anything is written to stdout.
"""
import argparse
import sys

import gmpy2
from fitlib import HEADER, dd, hexd, mp


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stdout', action='store_true', help='write the generated header to stdout (default)')
    parser.parse_args()
    mp.prec = 240
    constants = []
    with gmpy2.context(precision=240, round=gmpy2.RoundToNearest):
        for base in (2, 10):
            hi, lo = dd(1 / mp.log(base))
            reference = 1 / gmpy2.log(gmpy2.mpfr(base))
            error = abs((gmpy2.mpfr(hi) + gmpy2.mpfr(lo) - reference) / reference)
            if error > gmpy2.exp2(-105):
                raise RuntimeError('inverse log%d split exceeds 2^-105 relative error' % base)
            constants.append((base, hi, lo))
            sys.stderr.write('log%d reciprocal: relative error %.4g (mpmath and MPFR, 240 bits)\n' %
                             (base, float(error)))
    out = [HEADER, '''/**
 * @file
 * Private constants generated by tools/oracle/fit_logbase.py in the pinned
 * oracle image (`tools/oracle/oracle.py fit-logbase`). Do not edit.
 * Each reciprocal uses a nearest binary64 high part and residual low part;
 * independent MPFR checking bounds its relative error by 2^-105.
 */
#ifndef GHOTI_IO_GMATH_SRC_ELEMENTARY_LOGBASE_CONSTANTS_H
#define GHOTI_IO_GMATH_SRC_ELEMENTARY_LOGBASE_CONSTANTS_H

#include <ghoti.io/math/macros.h>
''']
    for base, hi, lo in constants:
        out.append('/* 1 / ln(%d), represented as HI + LO. */' % base)
        out.append('#define GMATH_LOG%d_INV_HI %s' % (base, hexd(hi)))
        out.append('#define GMATH_LOG%d_INV_LO %s' % (base, hexd(lo)))
        out.append('')
    out.append('#endif /* GHOTI_IO_GMATH_SRC_ELEMENTARY_LOGBASE_CONSTANTS_H */')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
