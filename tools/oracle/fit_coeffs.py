"""Print the reduction constants of gmath_sin, gmath_cos and gmath_tan:
src/elementary/trig_tables.h.

Runs in the pinned oracle image (tools/oracle/oracle.py fit).  Everything it
prints is computed here, from mpmath at 400 bits; no library's tables or code
were read.  The kernel's own table and polynomial tails are a different file,
src/elementary/trig_kernel_table.h, printed by fit_kernel.py (`make oracle-fit`
runs both).

Printed: the bits of 2/pi as 32-bit words for the Payne-Hanek reduction
(Payne and Hanek, 1983) and pi/2 as a double-double.  For the fast reduction of
moderate arguments (Cody and Waite, 1980; Muller, Elementary Functions,
chapter 11): 2/pi as a double, and pi/2 split as P1 + P2 + P3 + P4 with P1..P3
of 33 significant bits each, so that n * Pk is exact for any n below 2^20, and
P4 the double nearest the remainder.  For arguments from 2^20 to below 2^30,
the same with narrower parts so that n * Pk is exact for n below 2^30: pi/2 as
Q1 + ... + Q5 of 23 significant bits each plus Q6, the double nearest the
remainder.
"""

import sys

from mpmath import mp, mpf, pi

mp.prec = 400

LIMBS = 42  # 32-bit words of 2/pi: 1344 bits, DBL_MAX needs 38 + 2


def dd_split(v):
    hi = float(v)
    lo = float(v - mpf(hi))
    return hi, lo


def round_bits(v, bits):
    """v rounded to the nearest number with the given count of significant bits."""
    e = int(mp.floor(mp.log(abs(v), 2)))
    scale = mpf(2) ** (bits - 1 - e)
    return mp.nint(v * scale) / scale


def hexd(d):
    return float(d).hex()


def main():
    limbs = []
    with mp.workprec(32 * LIMBS + 200):
        v = 2 / pi
        for _ in range(LIMBS):
            v *= 2**32
            w = int(mp.floor(v))
            limbs.append(w)
            v -= w
    pio2 = pi / 2
    p_hi, p_lo = dd_split(pio2)

    cw = []
    rem = pio2
    for _ in range(3):
        part = round_bits(rem, 33)
        cw.append(part)
        rem -= part
    cw.append(mpf(float(rem)))
    inv2pi = float(2 / pi)

    cw2 = []
    rem = pio2
    for _ in range(5):
        part = round_bits(rem, 23)
        cw2.append(part)
        rem -= part
    cw2.append(mpf(float(rem)))

