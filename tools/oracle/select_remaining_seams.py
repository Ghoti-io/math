def candidate_score(name,w,xword,yword=None):
 p,b,s,inf=params(w);x=decode(xword,w)
 if name in ('erf','erfc') and abs(x)>28:return None
 if name=='tgamma' and (x>=172 or x<=-256):return None
 if name in ('tgamma','lgamma') and x<=0 and x.denominator==1:return None
 y=decode(yword,w) if yword is not None else None
 bounds=[]
 for mode in [g.RoundDown,g.RoundUp]:
  with g.context(precision=256,round=mode):
   a=g.mpfr(x.numerator)/x.denominator
   v={'erf':g.erf,'erfc':g.erfc,'tgamma':g.gamma,'lgamma':lambda a:g.lgamma(a)[0],'powf':lambda a:a**(g.mpfr(y.numerator)/y.denominator)}[name](a)
   if not g.is_finite(v):return None
   bounds.append(rat(v))
 target=encode(bounds[0],w)
 if target!=encode(bounds[1],w) or not(target&(s-1)) or target&(s-1)>=inf:return None
 scores=[]
 for neighbor in [target-1,target+1]:
  if neighbor<0 or neighbor>=1<<w or neighbor&(s-1)>=inf:continue
  a=decode(target,w);c=decode(neighbor,w);unit=abs(c-a)
  if not unit:continue
  mid=(a+c)/2;lo,hi=bounds
  lower=F(0) if lo<=mid<=hi else min(abs(lo-mid),abs(hi-mid))/unit
  upper=max(abs(lo-mid),abs(hi-mid))/unit
  scores.append((upper,lower))
 return min(scores) if scores else None

