"""Compute the table and the polynomial of gmath_atan2 and print
src/elementary/atan2_table.h.

Runs in the pinned oracle image (tools/oracle/oracle.py fit-atan2, `make
oracle-fit`).  Everything printed is computed here with mpmath at 240 bits; no
library's tables or code were read.  The method is the table-driven arctangent
of Tang ("Table-driven implementation of the Expm1 function ...", 1992, and
Muller, Elementary Functions, chapter 11): for q = u/v in [1/8, 1] the nearest
multiple F of 1/64 is a row, and atan(F + beta) = atan(F) + G1 beta + G2
beta^2 + ... + G8 beta^8 is the Taylor series at F (|beta| <= 2^-7).  Row j
holds atan(F) as a double-double and G1 .. G8 as doubles.  Below 1/8 there is no
table: atan q = q + q^3 P(q^2), P of degree 6 fitted to be accurate relative to
q.
"""

import sys

from fitlib import HEADER, dd, fit, hexd, mp, mpf
from mpmath import atan, taylor, pi

sys.stderr.write("fit_atan2.py, mpmath at %d bits\n" % mp.prec)

ROWS = 128  # F = j/64, j = 0 .. 64; rows 0 .. 7 are never read (the direct path), rows 65 .. 127 are copies of row 64
TAYLOR = 8
DIRECT_LIMIT = mpf(1) / 8
DIRECT_DEGREE = 6


def main():
    def p(w):
        q = mp.sqrt(w)
        return (atan(q) - q) / (q * w)

    wmax = DIRECT_LIMIT**2 * mpf("1.001")
    pc = fit("atan: (atan q - q)/q^3 in w = q^2", p, DIRECT_DEGREE, mpf(2) ** -120, wmax, lambda w: w, m=120)

    out = []
    w = out.append
    w(HEADER)
    w("""/*
 * GENERATED by tools/oracle/fit_atan2.py in the pinned oracle image
 * (`make oracle-fit`).  Do not edit; regenerate.  Regenerating changes the
 * results, and so tests/corpus/trig.hash.  The method is described in the
 * comment above gmath_atan2 in atan2.c.
 */

#ifndef GHOTI_IO_GMATH_ATAN2_TABLE_H
#define GHOTI_IO_GMATH_ATAN2_TABLE_H

#include <ghoti.io/math/macros.h>

#include "elem_common.h"
""")
    w("#define GMATH_ATAN2_ROWS %d" % ROWS)
    w("#define GMATH_ATAN2_TAYLOR %d" % TAYLOR)
    w("#define GMATH_ATAN2_DIRECT_DEGREE %d" % DIRECT_DEGREE)
    w("/* pi/2 and pi as double-doubles, 3 pi/4 and pi/4 as the nearest doubles. */")
    for name, v in (("PIO2", pi / 2), ("PI", pi)):
        h, l = dd(v)
        w("#define GMATH_%s_HI %s" % (name, hexd(h)))
        w("#define GMATH_%s_LO %s" % (name, hexd(l)))
    w("#define GMATH_3PIO4 %s" % hexd(3 * pi / 4))
    w("#define GMATH_PIO4 %s" % hexd(pi / 4))
    w("")
    w("/* atan q = q + q^3 (P0 + P1 w + ... + P6 w^6), w = q^2, 0 <= q <= 1/8. */")
    w("static const double gmath_atan2_poly[GMATH_ATAN2_DIRECT_DEGREE + 1] = {%s};" % ", ".join(hexd(c) for c in pc))
    w("")
    w("/* Row j (j <= 64), F = j/64: atan F hi, atan F lo, G1 .. G8; rows 65 .. 127 repeat row 64. */")
    worst_all = mpf(0)
    w("GMATH_ALIGN16 static const double gmath_atan2_rows[GMATH_ATAN2_ROWS][2 + GMATH_ATAN2_TAYLOR] = {")
    for j in range(ROWS):
        F = mpf(min(j, 64)) / 64
        t = taylor(atan, F, TAYLOR)
        h, l = dd(t[0])
        vals = [h, l] + [float(c) for c in t[1:]]
        if 8 <= j <= 64:
            worst = mpf(0)
            for i in range(-40, 41):
                beta = mpf(i) / 40 * mpf(2) ** -7 * mpf("1.01")
                approx = mpf(h) + mpf(l)
                poly = mpf(0)
                for c in reversed(vals[2:]):
                    poly = poly * beta + mpf(c)
                approx += poly * beta
                worst = max(worst, abs(approx - atan(F + beta)) / atan(F + beta))
            assert worst < mpf(2) ** -57, (j, float(mp.log(worst, 2)))
            worst_all = max(worst_all, worst)
        w("  /* %2d */ {%s}," % (j, ", ".join(hexd(v) for v in vals)))
    w("};")
    sys.stderr.write("rows 8 .. 64: worst relative truncation error of the Taylor series 2^%.1f\n" % float(mp.log(worst_all, 2)))
    w("")
    w("#endif /* GHOTI_IO_GMATH_ATAN2_TABLE_H */")
    sys.stdout.write("\n".join(out) + "\n")


main()
