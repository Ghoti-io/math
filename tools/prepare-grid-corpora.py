"""Reconstruct deterministic grids, retaining pinned literal seeded answers.

The complete independently generated byte streams remain SHA256-pinned. Native
exact references reconstruct missing caches; a corrupt existing cache fails.
The manifest selects only families present in a particular source revision.
"""
import argparse
import hashlib
import importlib
import os
from pathlib import Path
import random
import re
import tempfile

FAMILIES = {
    'nearby': ('nearby_reference', 'nearbyint-special.corpus',
               'nearbyint-seeded.corpus', ['nearbyint-special.corpus', 'nearbyint.corpus'], 1),
    'currentint': ('current_ir_reference', 'currentint64-special.corpus',
                  'currentint64-seeded.corpus', ['currentint64-special.corpus'], 1),
    'fdim': ('positive_difference_reference', 'fdim64-special.corpus',
             'fdim64-seeded.corpus', ['fdim64-special.corpus', 'fdim.corpus'], 2),
}
SEED, COUNT = 20261028, 2000
PROVENANCE = {
    'nearby_reference': ('nearby', 'input nearest downward upward towardzero normalized-flags'),
    'current_ir_reference': ('currentint', 'input four-modes each signed32-result flags signed64-result flags'),
    'positive_difference_reference': ('positive_difference', 'x y nearest-result flags'),
}


def read(path):
    maximum = 8*1024*1024
    if not path.is_file() or not 0 < path.stat().st_size <= maximum:
        raise RuntimeError('grid file missing/nonregular/oversized: '+str(path))
    with path.open('rb') as stream:
        data = stream.read(maximum+1)
    if len(data) > maximum:
        raise RuntimeError('grid file grew beyond bound: '+str(path))
    return data


def digest(data):
    return hashlib.sha256(data).hexdigest()


def anchors(path, allowed):
    data = read(path)
    if b'\r' in data or not data.endswith(b'\n'):
        raise RuntimeError('noncanonical grid manifest')
    result = {}
    for line in data.decode('ascii').splitlines():
        match = re.fullmatch(r'([0-9a-f]{64})  ([a-z0-9.-]+)', line)
        if not match or match[2] not in allowed or match[2] in result:
            raise RuntimeError('grid manifest name/schema/duplicate differs')
        result[match[2]] = match[1]
    return result


def configuration(directory):
    allowed = {name for family in FAMILIES.values() for name in family[3]}
    expected = anchors(directory/'grid-payloads.sha256', allowed)
    active = []
    for name, family in FAMILIES.items():
        present = set(family[3]) & expected.keys()
        available = (Path(__file__).parent/(family[0]+'.py')).is_file()
        if (available and present != set(family[3])) or (present and not available):
            raise RuntimeError('grid family/source availability differs: '+name)
        if present:
            active.append((name, family))
    seed_names = {family[2] for _, family in active}
    seed_hashes = anchors(directory/'grid-seeds.sha256', seed_names)
    if not active or seed_hashes.keys() != seed_names:
        raise RuntimeError('grid seeded manifest population differs')
    return expected, seed_hashes, active


def seeded_words(arity):
    rng = random.Random(SEED ^ 64)
    if arity == 1:
        return {(rng.getrandbits(64),) for _ in range(COUNT)}
    words = set()
    for _ in range(COUNT):
        words.add((rng.getrandbits(64), rng.getrandbits(64)))
        x = rng.randrange(1, 0x7ff0000000000000-32)
        y = x+rng.randrange(1, 32)
        words.update([(y, x), (x | (1 << 63), y | (1 << 63))])
    return words


def seed_rows(directory, family, expected):
    data = read(directory/family[2])
    if digest(data) != expected:
        raise RuntimeError('literal grid seed SHA256 differs: '+family[2])
    lines = data.decode('ascii').splitlines()
    words = seeded_words(family[4])
    oracle, columns = PROVENANCE[family[0]]
    function = family[1].removesuffix('-special.corpus')+'-seeded'
    if len(lines) < 4 or lines[0] != '# Pinned oracle: '+oracle+' MPFR 4.2.2 gmpy2 2.3.2' or lines[1] != '# function '+function or lines[3] != '# '+columns:
        raise RuntimeError('literal grid seed provenance/schema differs')
    if len(lines) != len(words)+4 or lines[2] != (
            '# seed 20261028 count 2000 fresh false entries '+str(len(words))):
        raise RuntimeError('literal grid seed count differs')
    rows = {tuple(int(word, 16) for word in line.split()[:family[4]]): line
            for line in lines[4:]}
    if rows.keys() != words or len(rows) != len(lines)-4:
        raise RuntimeError('literal grid seed population differs')
    return rows


def check_seeds(lines, retained, arity):
    seen = set()
    for index, line in enumerate(lines[4:], 4):
        key = tuple(int(word, 16) for word in line.split()[:arity])
        if key in retained:
            if line != retained[key]:
                raise RuntimeError('literal seed disagrees with exact grid')
            lines[index] = retained[key]
            seen.add(key)
    if seen != retained.keys():
        raise RuntimeError('retained seed absent from exact grid')


def prepare(directory, verify_only=False):
    expected, seed_hashes, active = configuration(directory)
    retained = {name: seed_rows(directory, family, seed_hashes[family[2]])
                for name, family in active}
    missing = []
    for name, value in expected.items():
        path = directory/name
        if path.exists() or path.is_symlink():
            if digest(read(path)) != value:
                raise RuntimeError('existing grid cache SHA256 differs: '+name)
        else:
            missing.append(name)
    # Check the retained literal answers even on a warm cache. Updating a seed
    # and its small-file manifest must not bypass the independent full-grid pin.
    for name, family in active:
        if family[1] not in missing:
            check_seeds(read(directory/family[1]).decode('ascii').splitlines(),
                        retained[name], family[4])
    if verify_only and missing:
        raise RuntimeError('grid cache missing: '+', '.join(missing))
    data = {}
    for name, family in active:
        if not set(family[3]) & set(missing):
            continue
        payloads = importlib.import_module(family[0]).payloads(SEED, COUNT)
        lines = payloads[family[1]].splitlines()
        check_seeds(lines, retained[name], family[4])
        payloads[family[1]] = '\n'.join(lines)+'\n'
        for filename in family[3]:
            data[filename] = payloads[filename].encode('ascii')
            if digest(data[filename]) != expected[filename]:
                raise RuntimeError('reconstructed grid SHA256 differs: '+filename)
    for name in missing:
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=directory, prefix='.grid-cache-', delete=False) as stream:
                temporary = Path(stream.name)
                os.fchmod(stream.fileno(), 0o644)
                stream.write(data[name])
            try:
                os.link(temporary, directory/name)
            except FileExistsError:
                if digest(read(directory/name)) != expected[name]:
                    raise RuntimeError('grid cache changed during publication: '+name)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', type=Path, default=Path('tests/corpus'))
    parser.add_argument('--verify-only', action='store_true')
    parser.add_argument('--clean', action='store_true')
    args = parser.parse_args()
    if args.clean:
        expected, _, _ = configuration(args.directory)
        for name in expected:
            (args.directory/name).unlink(missing_ok=True)
        print('generated grid caches removed; literal seeded answers retained')
    else:
        prepare(args.directory, args.verify_only)
        print('complete pinned grids and literal seeded answers verified')


if __name__ == '__main__':
    try:
        main()
    except (OSError, UnicodeError, ValueError, RuntimeError) as error:
        raise SystemExit('grid cache: FAIL: '+str(error))
