"""Exact Taylor coefficients and independently bounded rational ln2 sum."""
import argparse
from fractions import Fraction
from pathlib import Path

def split(q):
    hi=float(q);lo=float(q-Fraction(hi));return '{%s, %s}'%(hi.hex(),lo.hex())
def content():
    z=Fraction(1,3)
    if z**80/(81*(1-z*z))>=Fraction(2)**-132:
        raise RuntimeError('logarithm tail bound failed')
    factorial26=1
    for n in range(1,27):factorial26*=n
    if 4*Fraction(347,1000)**25/factorial26>=Fraction(2)**-124:
        raise RuntimeError('exponential tail bound failed')
    # ln2=2*atanh(1/3). The remaining positive tail is <2^-405.
    ln2_tail=2*Fraction(1,3)**257/(257*(1-Fraction(1,9)))
    if ln2_tail>=Fraction(2)**-405:raise RuntimeError('ln2 tail bound failed')
    ln2=2*sum((Fraction(1,3)**(2*n+1)/ (2*n+1) for n in range(128)),Fraction())
    out=['/* SPDX-License-Identifier: LGPL-3.0-only */','/* Copyright (C) 2026 Corey Pennycuff */',
         '/* Generated by tools/gen-log1p-expm1-coefficients.py. */',
         '#ifndef GHOTI_IO_GMATH_LOG1P_EXPM1_COEFF_H','#define GHOTI_IO_GMATH_LOG1P_EXPM1_COEFF_H',
         '#include <ghoti.io/math/macros.h>',
         'static const gmath_pair plus_ln2 = '+split(ln2)+';',
         'static const gmath_pair plus_log_coeff[40] = {']
    out += ['  '+split(Fraction(1,2*n+1))+',' for n in range(40)]
    out+=['};','static const gmath_pair plus_exp_coeff[25] = {']
    factorial=1
    for n in range(1,26):
        factorial*=n;out.append('  '+split(Fraction(1,factorial))+',')
    out+=['};','#endif'];return '\n'.join(out)+'\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    path=Path(__file__).resolve().parents[1]/'src/elementary/log1p_expm1_coeff.h';text=content()
    if a.check:
        if path.read_text()!=text:raise SystemExit('log1p/expm1 coefficient drift')
    else:path.write_text(text)
