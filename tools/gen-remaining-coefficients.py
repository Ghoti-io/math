text+='#include <ghoti.io/math/macros.h>\n'
for n,v in values.items():text+='static const rmp %s=%s;\n'%(n,encode(v))
text+='static const rmp rm_stirling[64]={\n'+',\n'.join(encode(B[2*k]/F(2*k*(2*k-1))) for k in range(1,65))+'\n};\n'
