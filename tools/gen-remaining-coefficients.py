"""Own rational Machin pi, integer square root/log series, Bernoulli recurrence."""
import sys
if sys.flags.optimize:
 raise SystemExit('remaining-fifteen: optimized Python execution is unsupported')
from fractions import Fraction as F
from math import isqrt, comb
from pathlib import Path
import argparse
P=600;S=1<<P
# Integer fixed-point log: normalize to [1,2), then 2*atanh((x-1)/(x+1)).
def log(v):
    e=v.bit_length()-1-P
    x=v>>e if e>=0 else v<<-e
    z=(x-S)*S//(x+S);z2=z*z//S;t=z;v=0
    for k in range(1,1000,2):v+=t//k;t=t*z2//S
    return 2*v+e*ln2
ln2=0;t=S//3
for k in range(1,1000,2):ln2+=2*(t//k);t=t//9
pi=16*sum((F((-1)**k,(2*k+1)*5**(2*k+1)) for k in range(160)),F())-4*sum((F((-1)**k,(2*k+1)*239**(2*k+1)) for k in range(50)),F())
pii=pi.numerator*S//pi.denominator
values={'rm_ln2':F(ln2,S),'rm_pi':pi,'rm_logpi':F(log(pii),S),'rm_logsqrt2pi':F(log(2*pii),2*S),'rm_two_sqrtpi':F(2*S,isqrt(pii*S))}
# Certify construction error independently of point fixed-point evaluation.
# Machin's alternating first omitted term bounds pi. The log2 series has a
# positive geometric remainder. Log(pi)/log(2*pi) are then recomputed with
# outward integer intervals, including each multiplication/division rounding.
ln2_lo=2*sum((F(1,(2*k+1)*3**(2*k+1)) for k in range(220)),F())
ln2_hi=ln2_lo+F(2,441*3**441)*F(9,8)
pi_tail=F(16,321*5**321)+F(4,101*239**101)
pi_lo,pi_hi=pi-pi_tail,pi+pi_tail
assert pi_tail<F(2)**-740 and 3<pi_lo<pi_hi<4
assert max(abs(values['rm_ln2']-v) for v in [ln2_lo,ln2_hi])<F(2)**-580
ceildiv=lambda a,b:-(-a//b)
def log_interval(vlo,vhi):
    e=vlo.bit_length()-1-P
    assert e>=0 and vhi.bit_length()-1-P==e
    xl=vlo>>e;xh=ceildiv(vhi,1<<e)
    zl=(xl-S)*S//(xl+S);zh=ceildiv((xh-S)*S,xh+S)
    assert 0<=zl<=zh<=3*S//8
    z2l=zl*zl//S;z2h=ceildiv(zh*zh,S);tl,th=zl,zh;low=high=0
    for k in range(1,1000,2):
        low+=tl//k;high+=ceildiv(th,k);tl=tl*z2l//S;th=ceildiv(th*z2h,S)
    assert 2*F(3,8)**1001/F(1001)/(1-F(3,8)**2)<F(1,S)
    l2l=(ln2_lo*S).__floor__();l2h=(ln2_hi*S).__ceil__()
    return F(2*low+e*l2l,S),F(2*high+e*l2h+1,S)
logpi_interval=log_interval((pi_lo*S).__floor__(),(pi_hi*S).__ceil__())
log2pi_interval=log_interval((2*pi_lo*S).__floor__(),(2*pi_hi*S).__ceil__())
root=isqrt(pii*S);sqrt_lo=F(root-1,S);sqrt_hi=F(root+2,S)
assert sqrt_lo**2<pi_lo<pi_hi<sqrt_hi**2
intervals={'rm_ln2':(ln2_lo,ln2_hi),'rm_pi':(pi_lo,pi_hi),'rm_logpi':logpi_interval,'rm_logsqrt2pi':tuple(v/2 for v in log2pi_interval),'rm_two_sqrtpi':(2/sqrt_hi,2/sqrt_lo)}
for name,(lo,hi) in intervals.items():
    assert lo<=hi and hi-lo<F(2)**-580
    assert max(abs(values[name]-lo),abs(values[name]-hi))<F(2)**-578
    value=values[name];e=value.numerator.bit_length()-value.denominator.bit_length()
    if value<F(2)**e:e-=1
    unit=F(2)**(e-255);packed=(value/unit).__floor__()*unit
    assert max(abs(packed-lo),abs(packed-hi))<2*unit

B=[F(1)]
for n in range(1,131):B.append(-sum((F(comb(n+1,k))*B[k] for k in range(n)),F())/F(n+1))
def encode(x):
    s=int(x<0);x=abs(x);e=x.numerator.bit_length()-x.denominator.bit_length()
    if x<F(2)**e:e-=1
    q=int(x*F(2)**(255-e))
    return '{{'+','.join('UINT32_C(0x%08x)'%((q>>(32*i))&0xffffffff) for i in range(8))+'},%d,%d}'%(e,s)
# First omitted terms and continued-fraction parity gap, exact rationals.
from math import factorial
assert F(4)**321/F(factorial(160)*321)*2 < F(2)**-309
assert abs(B[130]/F(130*129)*F(64)**-129) < F(2)**-401
assert F(2)**203/F(factorial(203)) < F(2)**-1000  # pi/2 < 2
c0=F(0);c1=F(0)
for k in range(256,0,-1):c0=F(k,2)/(4+c0)
for k in range(257,0,-1):c1=F(k,2)/(4+c1)
assert abs((4+c0)/(4+c1)-1)<F(2)**-235
# Dispatch-tail certificates. erfc(t) < exp(-t*t)/(t*sqrt(pi));
# exp(49)>2^70 implies exp(784)=exp(49)^16>2^1120. Log-convexity
# and Gamma(3)>Gamma(2) imply gamma is increasing for x>=3.
exp49=sum((F(49)**k/F(factorial(k)) for k in range(200)),F())
assert exp49>F(2)**70
assert F(2)**-70<F(2)**-54       # erf >=7 rounds to1 in Double/Float
assert F(2)**-1120<F(2)**-1075   # erfc >=28 rounds to0
assert factorial(171)>2**1024   # gamma >=172 overflows
# Noninteger binary64 a>=256 has distance to an integer >=2^-44.
# sin(pi*f)>=2*f on[0,1/2], pi<4 and Gamma(1+a)>=256!.
assert F(2)**45/F(factorial(256))<F(2)**-1075

