"""Exact rational Taylor coefficients; no fitted or external implementation data."""
import argparse
from fractions import Fraction
from pathlib import Path

def content():
    lines = ['/* Generated by tools/gen-inverse-trig-coefficients.py. */',
             '/* asin(x)/x = sum binomial(2n,n) x^(2n)/(4^n(2n+1)). */',
             '#include <ghoti.io/math/macros.h>',
             'static const gmath_pair inverse_asin_coeff[33] = {']
    c = Fraction(1)
    for n in range(33):
        hi = float(c)
        lo = float(c - Fraction(hi))
        lines.append('  {%s, %s},' % (hi.hex(), lo.hex()))
        c *= Fraction((2*n+1)**2, 2*(n+1)*(2*n+3))
    lines.append('};')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true')
    a = p.parse_args(); path = Path(__file__).resolve().parents[1]/'src/elementary/inverse_trig_coeff.h'
    text = content()
    if a.check:
        if path.read_text() != text: raise SystemExit('inverse-trig coefficient drift')
    else: path.write_text(text)
