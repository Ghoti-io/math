"""Derive seventeen-family constants from rational identities only.

Machin: pi=16 atan(1/5)-4 atan(1/239). Each integer division is
outward; the alternating-series remainder is bounded by its next term.
No host math or oracle contributes a constant.
"""
import argparse, hashlib, json, math, os, sys
if not __debug__ or sys.flags.optimize:raise SystemExit("seventeen certificates require assertion-enabled Python")
from fractions import Fraction
from pathlib import Path
P=75008
F=4352
ROOT=Path(__file__).resolve().parents[1]
HEADER=ROOT/'src/elementary/long_double_seventeen_constants.h'

def atan_bounds(d, bits):
    scale=1<<bits
    power=d
    low=high=0
    n=0
    while True:
        denom=(2*n+1)*power
        q,r=divmod(scale,denom)
        if n&1:
            low-=q+bool(r);high-=q
        else:
            low+=q;high+=q+bool(r)
        n+=1;power*=d*d
        tail=(scale+(2*n+1)*power-1)//((2*n+1)*power)
        if tail<=1:
            if n&1:low-=tail
            else:high+=tail
            return low,high,n

def ln2_bounds(bits):
    scale=1<<bits;low=high=0;power=3;n=0
    while True:
        q,r=divmod(scale,(2*n+1)*power)
        low+=2*q;high+=2*(q+bool(r));n+=1;power*=9
        # 2*sum_{j>=n}t^(2j+1)/(2j+1)<=9/(4*(2n+1)*3^(2n+1)).
        denominator=4*(2*n+1)*power
        tail=(9*scale+denominator-1)//denominator
        if tail<=1:return low,high+tail,n

def cancellation_arithmetic_ledger():
    # Coefficients of u=2^-4352, derived in the root/grid proof document.
    # All cross terms are <=u since every intermediate coefficient is <2^64.
    product_relative=1024*8
    log_width=lambda relative:(1<<16)*relative+(1<<20)
    main=(1<<11)*log_width(0)+(1<<20)
    product_log=log_width(product_relative)
    constant=(1<<22)
    stirling=(1<<20)
    sine_relative=(1<<20)
    reflected_log=log_width(sine_relative)
    log_pi=log_width(4)
    final_rounding=(1<<20)
    pieces={'main':main,'product_log':product_log,'constant':constant,
            'stirling_arithmetic':stirling,'reflection_log_sine':reflected_log,
            'reflection_log_pi':log_pi,'final_rounding':final_rounding}
    total=sum(pieces.values())
    assert total<(1<<40)<(1<<64)
    assert (1<<128)<(1<<F) # validates absorption of second-order width products
    return pieces,total

def derive():
    bits=P+64
    a,b,an=atan_bounds(5,bits)
    c,d,cn=atan_bounds(239,bits)
    lo,hi=16*a-4*d,16*b-4*c
    assert lo>0 and hi>=lo
    scale=1<<bits
    invlo=((2<<P)*scale)//hi
    invhi=((2<<P)*scale)//lo
    assert invlo==invhi, 'insufficient division enclosure'
    pi_lo=lo>>(bits-F)
    pi_hi=(hi+(1<<(bits-F))-1)>>(bits-F)
    assert pi_hi==pi_lo+1
    # Separation certificates (k nonzero): for a supported x=A*2^-16494,
    # r=2*x/k has denominator b<=2^16494*|k|<=D. Since q>D and gcd(p,q)=1,
    # r!=p/q and |pi-r|>=1/(b*q)-1/(2*D*q)>=1/(2*b*q).
    # Therefore |x-k*pi/2|>=2^-16496/q>2^-49396.
    # Nearest-quadrant midpoints use r=4*x/k for odd k and b<=D, giving
    # |x-k*pi/4|>=2^-16495/q>2^-49395. k=0 uses exact x directly.
    # Convergents of an interior dyadic approximation. Certification below
    # uses both exact Machin endpoints, so no irrational CF assumption leaks.
    numerator,denominator=lo+hi,2*scale
    p0,p1,q0,q1=0,1,1,0
    D=1<<32879
    while denominator:
        quotient,remainder=divmod(numerator,denominator)
        pp,qq=quotient*p1+p0,quotient*q1+q0
        if qq>D and abs(lo*qq-pp*scale)*2*D<scale and abs(hi*qq-pp*scale)*2*D<scale:
            break
        p0,p1,q0,q1=p1,pp,q1,qq
        numerator,denominator=denominator,remainder
    else:raise AssertionError('no separation witness')
    assert math.gcd(pp,qq)==1 and D<qq<(1<<32900)
    def words(n,count):return [(n>>(32*i))&0xffffffff for i in range(count)]
    def array(name,data):
        return 'static const uint32_t '+name+'['+str(len(data))+'] = {\n'+''.join('  '+','.join('UINT32_C(0x%08x)'%x for x in data[i:i+6])+',\n' for i in range(0,len(data),6))+'};\n'
    out='/* SPDX-License-Identifier: LGPL-3.0-only\n * Copyright (C) 2026 Corey Pennycuff\n * Generated by tools/prepare-long-double-seventeen.py; rational bounds only. */\n#ifndef GHOTI_IO_GMATH_LONG_DOUBLE_SEVENTEEN_CONSTANTS_H\n#define GHOTI_IO_GMATH_LONG_DOUBLE_SEVENTEEN_CONSTANTS_H\n#include <ghoti.io/math/macros.h>\n#define LDS17_REDUCTION_BITS '+str(P)+'\n'
    out+=array('lds17_two_over_pi',words(invlo,P//32))
    out+=array('lds17_pi_floor',words(pi_lo,F//32+2))
    l2lo,l2hi,l2terms=ln2_bounds(F+64)
    ln2_floor=l2lo>>64
    assert (l2hi+(1<<64)-1)>>64==ln2_floor+1
    out+=array('lds17_ln2_floor',words(ln2_floor,F//32+2))
    # Stirling coefficients B_(2k)/(2k(2k-1)), with exact Bernoulli recurrence.
    # A fixed denominator2^F encloses each coefficient independently.
    bern=[Fraction(1)]
    coeff=[]
    for n in range(1,1025):
        bern.append(-sum(Fraction(math.comb(n+1,k))*bern[k] for k in range(n))/(n+1))
        if n%2==0:
            c=bern[n]/(n*(n-1));sign=c<0;c=abs(c)
            value=(c.numerator<<F)//c.denominator
            assert value.bit_length()<=F+8192
            coeff.append((sign,value))
    # Coefficients grow far beyond64 integer bits; normalized mantissas
    # retain4352 fractional bits with an explicit power-of-two exponent.
    exponents=[];signs=[];data=[]
    for sign,value in coeff:
        exponent=max(0,value.bit_length()-F-1)
        # Recompute directly from rational to retain an outward upper unit.
        c=abs(bern[2*(len(exponents)+1)]/((2*(len(exponents)+1))*(2*(len(exponents)+1)-1)))
        value=(c.numerator<<F)//(c.denominator<<exponent)
        exponents.append(exponent);signs.append(int(sign));data.extend(words(value,F//32+2))
    out+='static const unsigned short lds17_bernoulli_exponent[512] = {'+','.join(map(str,exponents))+'};\n'
    out+='static const unsigned char lds17_bernoulli_sign[512] = {'+','.join(map(str,signs))+'};\n'
    out+=array('lds17_bernoulli_floor',data)
    out+='#endif\n'
    # Adjacent positive Laplace CF convergents at x=16. All denominator
    # polynomials have positive coefficients, so their absolute gap decreases
    # for x>=16. On16<=x<128 the reciprocal fraction exceeds1/129.
    previous,current=1,32
    for n in range(1,2050):previous,current=current,32*current+2*n*previous
    cf_num=math.factorial(2049)<<2050
    cf_den=previous*current
    assert (cf_num<<2614)<cf_den
    assert (cf_num*129<<2606)<cf_den
    # Stieltjes remainder: at y>=1024 the first omitted positive term is
    # smaller than |B1024/(1024*1023)|*y^-1023/16. The new-family proof
    # budgets all finite-grid cancellation-region arithmetic at2^64 units.
    last=abs(bern[1024]/(1024*1023))
    stirling_tail=last/(16*1024**1023)
    assert stirling_tail*(1<<4190)<1
    arithmetic_ledger,arithmetic_total=cancellation_arithmetic_ledger()
    assert sum(Fraction(7**n,math.factorial(n))for n in range(21))>1026
    assert all(abs(bern[2*k]/((2*k)*(2*k-1)))>Fraction(1,1<<11)for k in range(1,513))
    arithmetic_width=Fraction(1,1<<(F-64))
    assert (stirling_tail+arithmetic_width)*(1<<4100)<1
    evidence={'precision':P,'machin_terms':[an,cn],'pi_width_units_at_work_precision':hi-lo,'witness_p_hex':hex(pp),'witness_q_hex':hex(qq),'witness_q_bits':qq.bit_length(),'separation_exponent':-49396,'midpoint_separation_exponent':-49395,'reduction_error_exponent':16384-P,'header_sha256':hashlib.sha256(out.encode()).hexdigest(),'cf_absolute_width_exponent':-2614,'cf_relative_width_exponent':-2606,'stirling_tail_exponent':-4190,'cancellation_region_arithmetic_units_exponent':64,'cancellation_region_absolute_width_exponent':-4100,'ln2_terms':l2terms,'cancellation_arithmetic_ledger_units':arithmetic_ledger,'cancellation_arithmetic_total_units':arithmetic_total}
    return out,evidence

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');ap.add_argument('--evidence',type=Path);ap.add_argument('--output',type=Path,default=HEADER);args=ap.parse_args()
    target=args.output
    out,evidence=derive()
    if args.check:
        if not target.exists() or target.read_bytes()!=out.encode():raise SystemExit('seventeen constants mismatch (no repair performed)')
    else:
        if target.exists():raise SystemExit('seventeen constants already exist; use --check (no repair performed)')
        descriptor=os.open(target,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o644)
        try:
            data=out.encode();position=0
            while position<len(data):
                written=os.write(descriptor,data[position:])
                if written<=0:raise OSError('short constant write')
                position+=written
            os.fsync(descriptor)
        finally:os.close(descriptor)
        if target.read_bytes()!=out.encode():raise SystemExit('constant write verification failed (no repair performed)')
    if args.evidence:args.evidence.write_text(json.dumps(evidence,sort_keys=True)+'\n')
    print('seventeen constants: exact Machin, reciprocal, separation and Bernoulli certificates pass; '+evidence['header_sha256'])
if __name__=='__main__':main()
